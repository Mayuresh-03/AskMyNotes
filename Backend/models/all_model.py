class SubjectShare(Base):
    """Tracks shared workspace access between users."""
    __tablename__ = "subject_shares"

    id = Column(Integer, primary_key=True, index=True)
    subject_id = Column(Integer, ForeignKey("subjects.id", ondelete="CASCADE"), nullable=False)
    shared_with_user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    role = Column(String, default="viewer")  # "viewer" or "editor"
    created_at = Column(DateTime, default=datetime.datetime.utcnow)


class SubjectAudioPodcast(Base):
    """Stores generated audio podcasts for subject summaries."""
    __tablename__ = "subject_audio_podcasts"

    id = Column(Integer, primary_key=True, index=True)
    subject_id = Column(Integer, ForeignKey("subjects.id", ondelete="CASCADE"), nullable=False)
    title = Column(String, nullable=False)
    audio_path = Column(String, nullable=False)
    transcript = Column(Text, nullable=True)
    created_at = Column(DateTime, default=datetime.datetime.utcnow)


class WeakSpotQuiz(Base):
    """Stores targeted adaptive quizzes generated for weak topics."""
    __tablename__ = "weak_spot_quizzes"

    id = Column(Integer, primary_key=True, index=True)
    subject_id = Column(Integer, ForeignKey("subjects.id", ondelete="CASCADE"), nullable=False)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    questions_json = Column(JSON, nullable=False)
    created_at = Column(DateTime, default=datetime.datetime.utcnow)