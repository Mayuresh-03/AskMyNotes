import datetime
from sqlalchemy import (
    Column,
    Integer,
    String,
    Text,
    DateTime,
    ForeignKey,
    Float,
    JSON,
    Boolean,
)
from sqlalchemy.orm import relationship
from pgvector.sqlalchemy import Vector
from database.postgresConn import Base


# -------------------- USER --------------------

class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    full_name = Column(String, nullable=True)
    email = Column(String, unique=True, index=True, nullable=False)
    hashed_password = Column(String, nullable=False)
    created_at = Column(DateTime, default=datetime.datetime.utcnow)

    # Password Reset Tokens
    reset_token = Column(String, nullable=True)
    reset_token_expiry = Column(DateTime, nullable=True)

    # Relationships
    subjects = relationship(
        "Subject",
        back_populates="user",
        cascade="all, delete-orphan"
    )

    practice_sessions = relationship(
        "PracticeSession",
        back_populates="user",
        cascade="all, delete-orphan"
    )


# -------------------- SUBJECT --------------------

class Subject(Base):
    __tablename__ = "subjects"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String, nullable=False)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    created_at = Column(DateTime, default=datetime.datetime.utcnow)

    # Relationships
    user = relationship("User", back_populates="subjects")
    notes = relationship(
        "Note",
        back_populates="subject",
        cascade="all, delete-orphan"
    )
    flashcards = relationship(
        "Flashcard",
        back_populates="subject",
        cascade="all, delete-orphan"
    )
    practice_sessions = relationship(
        "PracticeSession",
        back_populates="subject",
        cascade="all, delete-orphan"
    )


# -------------------- NOTES --------------------

class Note(Base):
    __tablename__ = "notes"

    id = Column(Integer, primary_key=True, index=True)
    file_name = Column(String, nullable=False)
    file_path = Column(String, nullable=False)
    subject_id = Column(Integer, ForeignKey("subjects.id", ondelete="CASCADE"), nullable=False)
    
    # Ingestion Status & Progress Tracking fields
    status = Column(String, default="processing")  # processing, completed, failed
    pages_processed = Column(Integer, default=0)
    total_pages = Column(Integer, default=0)
    
    created_at = Column(DateTime, default=datetime.datetime.utcnow)

    # Relationships
    subject = relationship("Subject", back_populates="notes")


# -------------------- NOTE EMBEDDINGS --------------------

class NoteEmbedding(Base):
    """
    Stores text chunks and vector embeddings generated by LlamaIndex.
    Uses 'data_note_embeddings' as created by PGVector / LlamaIndex context managers.
    """
    __tablename__ = "data_note_embeddings"

    id = Column(Integer, primary_key=True, index=True)
    text = Column(Text, nullable=False)
    metadata_ = Column("metadata_", JSON, nullable=True)
    # LlamaIndex PGVectorStore writes this on every insert. create_all will not
    # add it to a table that already exists; startup adds it if it is missing.
    node_id = Column(String, nullable=True)
    embedding = Column(Vector(1536), nullable=True)


# -------------------- FLASHCARDS --------------------

class Flashcard(Base):
    __tablename__ = "flashcards"

    id = Column(Integer, primary_key=True, index=True)
    subject_id = Column(Integer, ForeignKey("subjects.id", ondelete="CASCADE"), nullable=False)

    front = Column(Text, nullable=False)
    back = Column(Text, nullable=False)

    # Spaced repetition metadata
    difficulty = Column(String, default="Medium")
    last_reviewed = Column(DateTime, nullable=True)
    next_review = Column(DateTime, default=datetime.datetime.utcnow)

    created_at = Column(DateTime, default=datetime.datetime.utcnow)

    # Relationships
    subject = relationship("Subject", back_populates="flashcards")


# -------------------- PRACTICE SESSION --------------------

class PracticeSession(Base):
    """Tracks practice quiz score analytics per topic/subtopic."""
    __tablename__ = "practice_sessions"

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    subject_id = Column(Integer, ForeignKey("subjects.id", ondelete="CASCADE"), nullable=False)

    score = Column(Float, nullable=False)
    topic_data = Column(JSON, nullable=True)

    timestamp = Column(DateTime, default=datetime.datetime.utcnow)

    # Relationships
    user = relationship("User", back_populates="practice_sessions")
    subject = relationship("Subject", back_populates="practice_sessions")


